def add(unit, slug, title, overview, points, examples, analogy, questions, refs, calculations=()):
    number = len(LESSONS) + 1
    source_id = 'micro-' + slug
    knowledge = []
    for line in points.strip().splitlines():
        heading, explanation, takeaway, pitfall = line.strip().split('|')
        knowledge.append(dict(title=heading, explanation=explanation, key_takeaway=takeaway, pitfalls=[pitfall], source_ids=[source_id]))
    quiz = []
    for index, line in enumerate(questions.strip().splitlines()):
        fields = line.strip().split('|')
        if len(fields) != 9:
            raise ValueError(f'{slug} question {index}: expected question and four option/reason pairs')
        pairs = list(zip(fields[1::2], fields[2::2]))
        shift = index % 4
        pairs = pairs[-shift:] + pairs[:-shift] if shift else pairs
        level = '基础' if index < 6 else '应用' if index < 9 else '综合'
        explanation = '\n'.join(f'{chr(65+i)}（{"正确" if i == shift else "错误"}）：{reason}' for i, (_, reason) in enumerate(pairs))
        quiz.append(dict(question=f'【{level}】{fields[0]}', options=[p[0] for p in pairs], answer=shift, explanation=explanation))
    guide = dict(overview=overview + '\n\n' + NOTICE,
        objectives=['能解释并应用：' + point['title'] for point in knowledge],
        prerequisites=[LESSONS[-1]['title']] if LESSONS else ['会进行基本四则运算；无需网络设备实操经验'],
        knowledge_points=knowledge,
        worked_examples=[dict(title=f'例题 {i+1} · 分步推演', question=e[0], steps=e[1].split('；'), answer=e[2], mistake=e[3]) for i,e in enumerate(examples)],
        analogies=[dict(concept=title, scene=analogy[0], mapping=analogy[1].split('；'), limitation=analogy[2])], quiz=quiz)
    sources = [dict(id=source_id, label='微课堂配套原创讲义 · 非视频字幕或教材原文',
        text='\n\n'.join(p['title']+'：'+p['explanation'] for p in knowledge) + '\n\n' + NOTICE + '\n原视频（尚未核对字幕）：' + VIDEO + '\n课程背景：' + MOOC + '\n知识参考：\n' + '\n'.join(REFS[key][0]+' '+REFS[key][1] for key in refs))]
    LESSONS.append(dict(id='micro-v1-'+slug, course_id='microclass', unit=unit, number=number, title=title,
        minutes=35, guide=guide, sources=sources, calculation_indices=list(calculations)))


@lru_cache(maxsize=1)
def validated_lessons():
    result = {}
    for original in LESSONS:
        item = deepcopy(original)
        enrich(item, REFS)
        item['guide'] = StudyGuide.model_validate(item['guide']).model_dump()
        item['minutes'] = 45
        result[item['id']] = item
    return result


def content_fingerprint(guide, sources):
    value = json.dumps(dict(guide=guide, sources=sources), ensure_ascii=False,
                       sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(value.encode('utf-8')).hexdigest()


def refresh_saved_lessons(lesson_id=None):
    """Upgrade only an exact known shipped guide. Notes/answers/quiz indices stay intact.

    Foreign or edited imports are intentionally left alone, even with a built-in ID.
    Compare-and-swap protects concurrent updates without touching notes revisions.
    """
    lessons = validated_lessons()
    keys = [lesson_id] if lesson_id in lessons else list(lessons) if lesson_id is None else []
    if not keys:
        return 0
    changed = 0
    with db() as conn:
        rows = conn.execute('SELECT id,guide,sources FROM chapters WHERE id IN (' +
                            ','.join('?' for _ in keys) + ')', keys).fetchall()
        for row in rows:
            try:
                fingerprint = content_fingerprint(json.loads(row['guide']), json.loads(row['sources']))
            except (ValueError, TypeError):
                continue
            if fingerprint != ORIGINAL_CONTENT.get(row['id']):
                continue
            item = lessons[row['id']]
            cursor = conn.execute('UPDATE chapters SET guide=?,sources=? WHERE id=? AND guide=? AND sources=?',
                (dumps(item['guide']), dumps(item['sources']), row['id'], row['guide'], row['sources']))
            changed += cursor.rowcount
    return changed


def catalog():
    with db() as conn:
        rows = {r['id']: dict(r) for r in conn.execute('''SELECT c.id,c.completed,
            (SELECT COUNT(*) FROM attempts a WHERE a.chapter_id=c.id) attempted,
            (SELECT COUNT(*) FROM attempts a WHERE a.chapter_id=c.id AND a.correct=1) correct
            FROM chapters c WHERE c.id LIKE 'micro-v1-%' ''')}
    return dict(title='微课堂前三章 · 学懂再练', version=1, course_id='microclass', units=UNITS,
        description=NOTICE, source_url=VIDEO,
        lessons=[dict(id=i['id'], number=i['number'], unit=i['unit'], title=i['title'], overview=i['guide']['overview'],
            minutes=i['minutes'], questions=len(i['guide']['quiz']), topics=[p['title'] for p in i['guide']['knowledge_points']],
            started=i['id'] in rows, completed=bool(rows.get(i['id'], {}).get('completed')),
            attempted=rows.get(i['id'], {}).get('attempted', 0), correct=rows.get(i['id'], {}).get('correct', 0)) for i in validated_lessons().values()])


def open_lesson(lesson_id):
    item = validated_lessons().get(lesson_id)
    if not item:
        return None
    refresh_saved_lessons(lesson_id)
    with db() as conn:
        conn.execute('''INSERT OR IGNORE INTO chapters
            (id,course,textbook,title,mode,goal,guide,sources,created_at) VALUES (?,?,?,?,?,?,?,?,?)''',
            (item['id'], '计算机网络 · 微课堂配套', '前三章原创解析 v1 · 尚未逐节核对字幕',
             f"{item['number']:02d} · {item['title']}", 'demo', 'understand', dumps(item['guide']), dumps(item['sources']), now()))
    return {'chapter_id': item['id']}


