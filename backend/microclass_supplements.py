def enrich(item, references):
    """Apply once to a fresh guide before validation; never mutate quiz entries."""
    supplement = SUPPLEMENTS[item['id'].removeprefix('micro-v1-')]
    title, explanation, takeaway, pitfall = supplement['point']
    source_id = item['id'] + '-deeper'
    item['guide']['knowledge_points'].append(dict(title=title, explanation=explanation,
        key_takeaway=takeaway, pitfalls=[pitfall], source_ids=[source_id]))
    for question, steps, answer, mistake in supplement['examples']:
        number = len(item['guide']['worked_examples']) + 1
        item['guide']['worked_examples'].append(dict(title=f'例题 {number} · 迁移与辨析',
            question=question, steps=steps, answer=answer, mistake=mistake))
    item['guide']['objectives'].extend('闭卷自查：' + prompt for prompt in supplement['recall'])
    item['sources'].append(dict(id=source_id, label='进阶解析与复习自查 · 原创补充 2026-10-13',
        text=title+'\n'+explanation+'\n\n复习自查：\n'+'\n'.join(supplement['recall'])+
        '\n\n核对来源（例题参数与推演为原创）：\n'+'\n'.join(references[key][0]+' '+references[key][1] for key in supplement['refs'])))
