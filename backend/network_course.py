    guide = {
        'overview': overview,
        'objectives': [f'能解释：{point[0]}' for point in points],
        'prerequisites': [LESSONS[-1]['title']] if LESSONS else ['会进行基本四则运算；二进制会在课程中使用'],
        'knowledge_points': [dict(title=p[0], explanation=p[1], key_takeaway=p[2], pitfalls=[p[3]], source_ids=[source_id]) for p in points],
        'worked_examples': [dict(title='跟着步骤做一遍', question=example[0], steps=example[1], answer=example[2], mistake=example[3])],
        'analogies': [dict(concept=title, scene=analogy[0], mapping=analogy[1], limitation=analogy[2])],
        'quiz': [dict(question=q[0], options=q[1], answer=q[2], explanation=q[3]) for q in quiz],
    }
    sources = [dict(id=source_id, label='知章原创课程讲义 · 非教材原文', text='\n\n'.join(p[0] + '：' + p[1] for p in points) + ('\n\n延伸阅读（需联网）：\n' + '\n'.join(refs) if refs else ''))]
