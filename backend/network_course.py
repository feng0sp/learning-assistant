@lru_cache(maxsize=1)
def validated_lessons():
    for item in LESSONS:
        item['guide'] = StudyGuide.model_validate(item['guide']).model_dump()
    return {item['id']: item for item in LESSONS}


def catalog():
    lessons = validated_lessons()
    with db() as conn:
        rows = {r['id']: dict(r) for r in conn.execute('''SELECT c.id,c.completed,
            (SELECT COUNT(*) FROM attempts a WHERE a.chapter_id=c.id) attempted,
            (SELECT COUNT(*) FROM attempts a WHERE a.chapter_id=c.id AND a.correct=1) correct
            FROM chapters c''')}
    return {'title': '计算机网络 · 完整学习路径', 'version': 1,
            'description': '本科通用体系 · 原创精讲与练习 · 非指定教材逐页复刻。基础学习离线可用，AI 追问需要另行配置模型。',
            'units': UNITS, 'lessons': [dict(id=i['id'], number=i['number'], unit=i['unit'], title=i['title'],
                overview=i['guide']['overview'], minutes=i['minutes'], questions=len(i['guide']['quiz']),
                topics=[p['title'] for p in i['guide']['knowledge_points']],
                started=i['id'] in rows, completed=bool(rows.get(i['id'], {}).get('completed')),
                attempted=rows.get(i['id'], {}).get('attempted', 0), correct=rows.get(i['id'], {}).get('correct', 0)) for i in lessons.values()]}


def open_lesson(lesson_id):
    item = validated_lessons().get(lesson_id)
    if not item:
        return None
    with db() as conn:
        conn.execute('''INSERT OR IGNORE INTO chapters
            (id,course,textbook,title,mode,goal,guide,sources,created_at) VALUES (?,?,?,?,?,?,?,?,?)''',
            (item['id'], '计算机网络', '知章完整课程 · 原创讲义 v1', f"{item['number']:02d} · {item['title']}",
             'demo', 'understand', dumps(item['guide']), dumps(item['sources']), now()))
    return {'chapter_id': item['id']}


